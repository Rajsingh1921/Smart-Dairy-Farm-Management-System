// Guided first-time setup: creates the MySQL database + a dedicated app user with a random
// password, writes server/.env with a random JWT secret, and creates all tables.
//   npm run setup
// Non-interactive: npm run setup -- --host 127.0.0.1 --port 3306 --root-user root --root-password secret --db dairy_farm
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import readline from 'node:readline';
import { fileURLToPath } from 'node:url';
import mysql from 'mysql2/promise';

const here = path.dirname(fileURLToPath(import.meta.url));
const args = {};
process.argv.slice(2).forEach((a, i, arr) => { if (a.startsWith('--')) args[a.slice(2)] = arr[i + 1] && !arr[i + 1].startsWith('--') ? arr[i + 1] : ''; });
const envFile = path.resolve(args['env-out'] || path.join(here, '..', '.env'));

function ask(q, { hidden = false, def = '' } = {}) {
  const rl = readline.createInterface({ input: process.stdin, output: process.stdout, terminal: true });
  const label = def ? `${q} [${def}]: ` : `${q}: `;
  if (hidden) rl._writeToOutput = (s) => rl.output.write(s.includes(label) ? s : '*');
  return new Promise((res) => rl.question(label, (a) => { rl.close(); if (hidden) process.stdout.write('\n'); res(a.trim() || def); }));
}
const val = async (key, q, opts) => (args[key] !== undefined ? args[key] : ask(q, opts));

async function main() {
  console.log('\nSmart Dairy Farm Manager - database setup\n');
  if (fs.existsSync(envFile) && args.force === undefined) {
    console.log(`${envFile} already exists. Nothing changed.\nTo redo setup, delete it or run: npm run setup -- --force`);
    return;
  }
  const host = await val('host', 'MySQL host', { def: '127.0.0.1' });
  const port = Number(await val('port', 'MySQL port', { def: '3306' }));
  const rootUser = await val('root-user', 'MySQL admin user (used once, not saved)', { def: 'root' });
  const rootPassword = await val('root-password', 'MySQL admin password (not saved)', { hidden: true });
  const db = await val('db', 'Database name to create', { def: 'dairy_farm' });
  if (!/^[a-zA-Z0-9_]{1,64}$/.test(db)) throw new Error('Database name may only contain letters, numbers and _');
  // One MySQL user per database, so setting up a second database never changes the first one's password.
  const appUser = args['app-user'] || `${db.slice(0, 28)}_app`;
  const appPassword = crypto.randomBytes(18).toString('base64url');

  const conn = await mysql.createConnection({ host, port, user: rootUser, password: rootPassword });
  try {
    await conn.query(`CREATE DATABASE IF NOT EXISTS \`${db}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci`);
    for (const h of ['localhost', '127.0.0.1', '::1']) {
      await conn.query('CREATE USER IF NOT EXISTS ?@? IDENTIFIED BY ?', [appUser, h, appPassword]);
      await conn.query('ALTER USER ?@? IDENTIFIED BY ?', [appUser, h, appPassword]);
      // Only this database, only the privileges the app needs.
      await conn.query(`GRANT SELECT, INSERT, UPDATE, DELETE, CREATE, ALTER, INDEX, DROP, REFERENCES, LOCK TABLES ON \`${db}\`.* TO ?@?`, [appUser, h]);
    }
  } finally {
    await conn.end();
  }

  const env = `# Generated by "npm run setup" on ${new Date().toISOString()}. Keep this file private.
NODE_ENV=production
PORT=4000
DB_HOST=${host}
DB_PORT=${port}
DB_USER=${appUser}
DB_PASSWORD=${appPassword}
DB_NAME=${db}
JWT_SECRET=${crypto.randomBytes(48).toString('hex')}
SESSION_HOURS=12
# Optional extra protection for the first-run owner setup page:
SETUP_TOKEN=
# false = allow login over plain http (e.g. http://192.168.1.10:4000 on the farm Wi-Fi).
# Set to true once you serve the app over https.
COOKIE_SECURE=false
TRUST_PROXY=false
CORS_ORIGIN=
UPLOAD_DIR=uploads
`;
  fs.writeFileSync(envFile, env, { mode: 0o600 });
  console.log(`\nCreated database "${db}" and MySQL user "${appUser}" (random password).\nWrote ${envFile}`);

  // Load the new settings and create tables.
  for (const line of env.split('\n')) { const m = /^([A-Z_]+)=(.*)$/.exec(line); if (m) process.env[m[1]] = m[2]; }
  const { migrate } = await import('../src/migrate.js');
  await migrate();
  console.log('\nDone. Next: npm start, then open http://localhost:4000 and create the owner account.');
}

main().catch((e) => { console.error('\nSetup failed:', e.message); process.exitCode = 1; });
